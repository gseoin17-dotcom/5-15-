def format_gold(amount):
    if amount == 0:
        return "0원"
    
    units = ["", "만", "억", "조", "경", "해"]
    result = []
    
    unit_idx = 0
    while amount > 0 and unit_idx < len(units):
        remainder = amount % 10000
        if remainder > 0:
            result.insert(0, f"{remainder:,}{units[unit_idx]}")
        amount //= 10000
        unit_idx += 1
        
    return "".join(result) + "원"

